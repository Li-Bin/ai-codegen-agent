# -*- coding: utf-8 -*-
"""
tests/conftest.py — 容差常數與共用工具（協定 §5.1）

【為什麼容差集中在這裡】
    協定 §5.4 禁止各測試就地寫死容差。原因：AI（或人）最常見的作弊
    是把某條測試的容差偷偷放寬到「剛好通過」。容差集中在單一檔案，
    diff 一眼就能看出有沒有人動過判準。

【每個常數的依據】
    數值不是拍腦袋，是先跑過正確參考實作量測後、留安全餘裕訂出來的。
    量測環境：numpy 2.4.4, float64。
"""
import numpy as np

# ---------------------------------------------------------------------------
# 容差常數（協定 §5.1，v1.2）
# ---------------------------------------------------------------------------

# 理論上精確、且訊號為單位尺度（|x|~1）的關係：rfft→irfft 往返。
# 實測往返誤差 ~1e-16，取 1e-12 留四個數量級餘裕。
# 若這條都過不了，代表實作根本不是在做 FFT/IFFT。
ATOL_EXACT = 1e-12

# 尺度相依的精確恆等式（Parseval、線性）用「相對」容差。
# 為什麼不能用絕對容差：能量 Σx² 隨振幅平方與 N 成長，|x|≤10、N=200
# 時能量可到 2e4，float64 的相對誤差 ~1e-15 換算成絕對誤差就超過
# 1e-12——用絕對容差會把正確實作誤判為 fail。
# 1e-9 仍足以抓到任何 1/N 正規化錯誤（那會差 N 倍，不是 1e-9 倍）。
RTOL_EXACT = 1e-9

# 頻率精確對齊 bin 時，陷波濾除後的還原誤差上限。
# 實測正確實作為 ~5.4e-15，取 1e-10 留餘裕。
ATOL_ALIGNED = 1e-10

# 頻率「不」對齊 bin（頻譜洩漏）時的雙邊界限，以 main_amp 為尺度。
# 這組數字由失敗模式校準得出（spec: f_main=137, f_noise=311, N=256,
# fs=1000, A_noise=0.4，全為定值 → 結果確定性）：
#     正確實作（notch 掉 bin 79+80）  rmse = 0.1156  ← 必須落在窗內
#     只移除一個 bin（部分修復）      rmse = 0.1792  ← 超過上限，fail
#     完全沒濾（no-op）               rmse = 0.2827  ← 超過上限，fail
#     濾錯目標（把主訊號濾掉）        rmse = 0.7552  ← 超過上限，fail
#     偷改參數成對齊 bin（作弊）      rmse ~ 1e-15   ← 低於下限，fail
# 窗 (0.02, 0.16) 對正確值留有上下兩側餘裕，同時擋掉全部已知失敗模式。
RTOL_LEAK_MIN = 0.02
RTOL_LEAKY = 0.16

# ---------------------------------------------------------------------------
# 共用工具
# ---------------------------------------------------------------------------

def make_spec(**kw):
    """
    產生測試用 SignalSpec 的預設參數組。

    預設值的講究：
      fs=1000, N=512 → Δf = 1000/512 = 1.953125，在二進位浮點下「精確」
      （512 是 2 的冪，除法不損失精度），對齊測試不會被浮點雜訊干擾。
    """
    from ifft_sim.core.types import SignalSpec
    base = dict(
        main_freq_hz=50.0,
        noise_freq_hz=125.0,
        n_samples=512,
        sample_rate_hz=1000.0,
        main_amp=1.0,
        noise_amp=0.4,
    )
    return SignalSpec(**{**base, **kw})


def align_to_bin(freq_hz: float, df_hz: float) -> float:
    """把頻率捨入到最近的 bin 整數倍（給對齊型測試用）。"""
    return round(freq_hz / df_hz) * df_hz
